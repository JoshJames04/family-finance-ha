"""Issue #43 — read-only structural inspection of the real workbook.

Emits STRUCTURE ONLY: sheet inventory, dims, cell-type signatures,
redacted formula patterns, named ranges, validation ranges, defect
locations. No cell values ever leave the machine — numeric literals
inside formulas are redacted to ``#`` and personal sheet names are
replaced by stable role aliases in the committed output.

Outputs (repo-relative):
  docs/migration-inventory.md        — pseudonymised, committable
  backend/tests/fixtures/workbook-structure.json — structure spec
  data/migration-map.local.json      — real sheet names → aliases
                                       (gitignored, extractor lookup)

Usage:
  python tools/inspect_workbook.py "path/to/Family Budget.xlsx"
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from openpyxl import load_workbook
from openpyxl.utils import get_column_letter

REPO = Path(__file__).resolve().parent.parent
OUT_DOC = REPO / "docs" / "migration-inventory.md"
OUT_SPEC = REPO / "backend" / "tests" / "fixtures" / "workbook-structure.json"
OUT_MAP = REPO / "data" / "migration-map.local.json"

# Real sheet names containing personal identifiers → neutral aliases.
# The inspector matches substrings case-insensitively; anything not
# listed keeps its real (non-personal) title.
ALIAS_RULES: list[tuple[str, str]] = [
    ("chloe", "MEMBER2_BUDGET"),
    ("mam's payments", "FAMILY_LOAN_LEDGER"),
    ("mams payments", "FAMILY_LOAN_LEDGER"),
]

_NUM = re.compile(r"\d+(?:\.\d+)?")
_ERR = re.compile(r"#[A-Z!/?]+")


def alias(title: str) -> str:
    low = title.lower()
    for pat, name in ALIAS_RULES:
        if pat in low:
            return name
    return title


def redact_formula(f: str) -> str:
    """Keep refs/functions; redact literal numbers and error args."""
    out = _NUM.sub("#", f)
    return out


def cell_kind(v: object) -> str:
    if v is None:
        return "."
    if isinstance(v, str):
        if v.startswith("="):
            return "f"
        if v.startswith("#"):
            return "e"  # error literal
        return "s"
    if isinstance(v, bool):
        return "b"
    return "n"


def sheet_signature(ws, max_scan: int = 40) -> dict:
    """Row/column cell-KIND signatures — no values, just shapes."""
    rows = []
    formula_cols: set[int] = set()
    literal_in_formula_col: list[str] = []
    errors: list[str] = []
    hardcoded_formula_cells: list[str] = []

    n_rows = min(ws.max_row or 0, ws.max_row or 0)
    n_cols = ws.max_column or 0
    # pass 1: map formula columns
    grid: dict[tuple[int, int], str] = {}
    for r in range(1, min(n_rows, max_scan) + 1):
        kinds = []
        for c in range(1, n_cols + 1):
            cell = ws.cell(row=r, column=c)
            v = cell.value
            k = cell_kind(v)
            kinds.append(k)
            grid[(r, c)] = v if k == "f" else ""
            if k == "f":
                formula_cols.add(c)
                if _NUM.search(v) and not _ERR.search(v):
                    hardcoded_formula_cells.append(
                        f"{get_column_letter(c)}{r}")
            elif k == "e":
                errors.append(f"{get_column_letter(c)}{r}")
        rows.append("".join(kinds))
    # pass 2: literals sitting in a formula column (defect E)
    for (r, c), v in grid.items():
        k = cell_kind(v)
        if k not in ("f", ".", "e") and c in formula_cols:
            literal_in_formula_col.append(f"{get_column_letter(c)}{r}")

    merged = [str(m) for m in ws.merged_cells.ranges]
    validations = [
        {"sqref": str(dv.sqref), "type": str(dv.type)}
        for dv in ws.data_validations.dataValidation
    ] if ws.data_validations else []
    comments = sum(
        1 for row in ws.iter_rows() for c in row if c.comment)
    formula_patterns = {}
    for (r, c), f in sorted(grid.items()):
        if f:
            pat = redact_formula(f)
            formula_patterns.setdefault(pat, []).append(
                f"{get_column_letter(c)}{r}")
    return {
        "signature_rows": rows,
        "formula_cols": sorted(formula_cols),
        "literal_in_formula_col": literal_in_formula_col[:50],
        "error_cells": errors[:50],
        "hardcoded_formula_cells": hardcoded_formula_cells[:50],
        "merged": merged[:50],
        "validations": validations[:30],
        "comment_cells": comments,
        "formula_patterns": {
            p: locs[:12] for p, locs in
            sorted(formula_patterns.items(),
                   key=lambda kv: -len(kv[1]))[:20]},
    }


def main(path: Path) -> None:
    wb = load_workbook(path, read_only=False, data_only=False)
    name_map = {ws.title: alias(ws.title) for ws in wb.worksheets}
    doc = ["# Workbook structural inventory (issue #43)", "",
           "Generated by `tools/inspect_workbook.py` — structure only,",
           "no cell values. Personal sheet names are pseudonymised;",
           "the real-name mapping lives in `data/migration-map.local.json`",
           "(gitignored).", "",
           f"| Sheet alias | State | Used range | Comments |",
           "|---|---|---|---|"]
    spec: dict = {"sheets": {}, "defined_names": {}}
    for ws in wb.worksheets:
        sig = sheet_signature(ws)
        a = name_map[ws.title]
        spec["sheets"][a] = {
            "state": ws.sheet_state,
            "dimensions": ws.calculate_dimension(),
            **sig,
        }
        doc.append(
            f"| `{a}` | {ws.sheet_state} | "
            f"{ws.calculate_dimension()} | {sig['comment_cells']} |")
    for name, dn in wb.defined_names.items():
        spec["defined_names"][name] = redact_formula(str(dn.attr_text))
    doc += ["", "## Defined names", ""]
    for n, ref in spec["defined_names"].items():
        doc.append(f"- `{n}` → `{redact_formula(ref)}`")
    doc += ["", "## Per-sheet structure", ""]
    for a, s in spec["sheets"].items():
        doc += [f"### `{a}` ({s['state']})",
                f"- dims `{s['dimensions']}`, merged {s['merged']}",
                f"- formula columns: {s['formula_cols']}",
                f"- literals inside formula columns "
                f"({len(s['literal_in_formula_col'])}): "
                f"{s['literal_in_formula_col'][:15]}",
                f"- hardcoded-constant formulas "
                f"({len(s['hardcoded_formula_cells'])}): "
                f"{s['hardcoded_formula_cells'][:15]}",
                f"- error cells ({len(s['error_cells'])}): "
                f"{s['error_cells'][:15]}",
                f"- validations: {s['validations'][:6]}",
                "- top formula patterns:"]
        for p, locs in list(s["formula_patterns"].items())[:8]:
            doc.append(f"    - `{p}` ×{len(locs)} @ {locs[:6]}")
        doc.append("")

    OUT_DOC.write_text("\n".join(doc), encoding="utf-8")
    OUT_SPEC.parent.mkdir(parents=True, exist_ok=True)
    OUT_SPEC.write_text(json.dumps(spec, indent=2), encoding="utf-8")
    OUT_MAP.parent.mkdir(parents=True, exist_ok=True)
    OUT_MAP.write_text(
        json.dumps({"sheet_aliases": {v: k for k, v in
                                      name_map.items()}},
                   indent=2), encoding="utf-8")
    print(f"sheets: {len(spec['sheets'])} "
          f"(hidden: {sum(1 for s in spec['sheets'].values() if s['state'] != 'visible')})")
    print(f"names: {len(spec['defined_names'])}")
    print(f"-> {OUT_DOC.relative_to(REPO)}")
    print(f"-> {OUT_SPEC.relative_to(REPO)}")
    print(f"-> {OUT_MAP.relative_to(REPO)} (gitignored)")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
